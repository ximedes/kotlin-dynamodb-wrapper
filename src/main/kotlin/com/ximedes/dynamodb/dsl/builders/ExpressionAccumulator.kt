package com.ximedes.dynamodb.dsl.builders

import software.amazon.awssdk.services.dynamodb.model.AttributeValue

/**
 * Collects the expression attribute names and values belonging to a single DynamoDB request.
 *
 * A request can carry more than one expression at a time — a key condition together with a filter,
 * or an update together with a condition — but it has only one `ExpressionAttributeNames` and one
 * `ExpressionAttributeValues` map to hold their placeholders. All expressions on a request must
 * therefore be rendered by the *same* [ExpressionRenderer]: rendering them separately restarts the
 * placeholder counters at `#n1` / `:v1` for each expression, so merging the results silently
 * overwrites the entries of whichever expression was rendered first.
 *
 * Instances are created with the setters of the request's SDK builder, which are re-applied
 * whenever the accumulated maps change.
 */
internal class ExpressionAccumulator(
    private val applyValues: (Map<String, AttributeValue>) -> Unit,
    private val applyNames: (Map<String, String>) -> Unit
) {
    private val renderer = ExpressionRenderer()

    private val values = mutableMapOf<String, AttributeValue>()
    private val names = mutableMapOf<String, String>()

    private val manualValueKeys = mutableSetOf<String>()
    private val manualNameKeys = mutableSetOf<String>()

    /** Renders a condition expression, allocating placeholders that no other expression uses. */
    fun condition(init: ConditionBuilder.() -> Condition): String =
        renderer.renderCondition(ConditionBuilder().init()).also { collectGenerated() }

    /** Renders an update expression, allocating placeholders that no other expression uses. */
    fun update(init: UpdateExpressionBuilder.() -> Unit): String =
        renderer.renderUpdate(UpdateExpressionBuilder().apply(init).build()).also { collectGenerated() }

    /** Adds attribute values supplied by hand, for use with a manually written expression. */
    fun attributeValues(manual: Map<String, AttributeValue>) {
        if (manual.isEmpty()) return
        val clashing = manual.keys.filter { it in renderer.attributeValues }
        require(clashing.isEmpty()) { clashMessage("value", clashing) }
        manualValueKeys.addAll(manual.keys)
        values.putAll(manual)
        applyValues(values)
    }

    /** Adds attribute names supplied by hand, for use with a manually written expression. */
    fun attributeNames(manual: Map<String, String>) {
        if (manual.isEmpty()) return
        val clashing = manual.keys.filter { it in renderer.attributeNames }
        require(clashing.isEmpty()) { clashMessage("name", clashing) }
        manualNameKeys.addAll(manual.keys)
        names.putAll(manual)
        applyNames(names)
    }

    private fun collectGenerated() {
        val clashingValues = renderer.attributeValues.keys.filter { it in manualValueKeys }
        require(clashingValues.isEmpty()) { clashMessage("value", clashingValues) }
        val clashingNames = renderer.attributeNames.keys.filter { it in manualNameKeys }
        require(clashingNames.isEmpty()) { clashMessage("name", clashingNames) }

        values.putAll(renderer.attributeValues)
        names.putAll(renderer.attributeNames)
        if (values.isNotEmpty()) applyValues(values)
        if (names.isNotEmpty()) applyNames(names)
    }

    private fun clashMessage(kind: String, placeholders: List<String>) =
        "Attribute $kind placeholder(s) ${placeholders.joinToString()} are generated by the " +
            "expression DSL; pick a different placeholder for the manually supplied attribute $kind."
}
